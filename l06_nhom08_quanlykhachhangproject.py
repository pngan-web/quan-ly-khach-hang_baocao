def do(ham, so_lan):
    """Chạy `so_lan` lần, trả về (trung bình, độ lệch chuẩn) bằng giây."""
    t = []
    for _ in range(so_lan):
        a = time.perf_counter(); ham(); t.append(time.perf_counter() - a)
    return statistics.mean(t), (statistics.stdev(t) if len(t) > 1 else 0.0)

